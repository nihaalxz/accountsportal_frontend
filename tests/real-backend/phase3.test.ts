	test('Expense Claim Workflows (Filing, Submission, Gated Approval)', async ({ page }) => {
		// Login as Accountant to file a Claim
		await page.goto('/login');
		await page.fill('#email', 'accountant@texas.com');
		await page.fill('#password', 'AccountantPass123!');
		await page.click('button[type="submit"]');
		await page.waitForURL(/.*dashboard/);

		// Go to Expenses list
		await page.goto('/expenses');
		await expect(page.locator('h1')).toContainText(/Expense Claims/i);

		// Click Log Expense
		await page.locator('button:has-text("Log Expense"), a:has-text("Log Expense")').click();
		await page.waitForURL(/.*expenses\/new/);

		// Fill the form
		const categorySelect = page.locator('#expenseCategoryId');
		await expect(categorySelect).toBeEnabled({ timeout: 10_000 });
		await categorySelect.selectOption({ index: 1 });
		await page.fill('#amount', '25.500');
		await page.fill('#expenseDate', '2026-07-14');
		await page.selectOption('#paymentMethod', 'cash');
		const sourceSelect = page.locator('#sourceAccountId');
		await expect(sourceSelect).toBeEnabled({ timeout: 10_000 });
		await sourceSelect.selectOption({ index: 1 });
		await page.fill('#description', `E2E Expense claim desc ${Date.now()}`);
		await page.fill('#notes', 'E2E operational notes.');
		await page.click('button[type="submit"]');

		// Redirect back to list
		await page.waitForURL(/.*expenses(?!\/new)/, { timeout: 15_000 });

		// Go to details of the newly created claim
		const newestRow = page.locator('tbody tr').first();
		await expect(newestRow).toBeVisible({ timeout: 5000 });
		await newestRow.click();

		await page.waitForURL(/.*expenses\/\d+/);
		await expect(page.locator('h2')).toBeVisible();

		// Submit the expense for approval
		const submitBtn = page.locator('button:has-text("Submit for Approval")');
		await expect(submitBtn).toBeVisible();
		await submitBtn.click();

		const confirmBtn = page.locator(
			'button:has-text("Yes, Submit Claim"), button:has-text("Yes, Close & Lock")'
		);
		await expect(confirmBtn).toBeVisible();
		await confirmBtn.click();

		// Reload details
		await expect(page.locator('span:has-text("Pending Approval")')).toBeVisible({
			timeout: 10_000
		});

		// Sign out and login as Master Accountant to Approve
		await page.click('button[title="Sign out"]');
		await page.waitForURL(/.*login/);

		await page.fill('#email', 'admin@texas.com');
		await page.fill('#password', 'S3cure_Acc_999!');
		await page.click('button[type="submit"]');
		await page.waitForURL(/.*dashboard/);

		// Go back to the expense page directly (using context path)
		await page.goto(page.url().replace('/dashboard', '/expenses'));
		await page.waitForURL(/.*expenses/);
		await page.locator('tbody tr').first().click();
		await page.waitForURL(/.*expenses\/\d+/);

		// Approve
		const approveBtn = page.locator('button:has-text("Approve")');
		await expect(approveBtn).toBeVisible();
		await approveBtn.click();

		const confirmApproveBtn = page.locator('button:has-text("Confirm Payout")');
		await expect(confirmApproveBtn).toBeVisible();
		await confirmApproveBtn.click();

		// Verify posted status
		await expect(page.locator('span:has-text("Posted")')).toBeVisible({ timeout: 10_000 });
	});

	test('Journal Entry Workflows (Create balanced, Post, Reverse)', async ({ page }) => {
		// Login as Accountant to create Journal
		await page.goto('/login');
		await page.fill('#email', 'accountant@texas.com');
		await page.fill('#password', 'AccountantPass123!');
		await page.click('button[type="submit"]');
		await page.waitForURL(/.*dashboard/);

		await page.goto('/accounting/journals');
		await page
			.locator('button:has-text("New Journal Entry"), a:has-text("New Journal Entry")')
			.click();
		await page.waitForURL(/.*journals\/new/);

		// Journal editor input
		await page.fill('#description', `E2E Journal Balanced ${Date.now()}`);
		await page.fill('#reference', `JNL-REF-${Date.now()}`);

		// Populate 2 balanced rows
		// Line 1: Debit
		const line1 = page.locator('tbody tr').nth(0);
		await line1.locator('select').first().selectOption({ index: 1 });
		await line1.locator('input[placeholder="0.000"]').first().fill('100.000'); // Debit input

		// Line 2: Credit
		const line2 = page.locator('tbody tr').nth(1);
		await line2.locator('select').first().selectOption({ index: 2 });
		await line2.locator('input[placeholder="0.000"]').nth(1).fill('100.000'); // Credit input

		// Submit draft
		await page.click('button[type="submit"]');

		// Redirect to journal list
		await page.waitForURL(/.*journals(?!\/new)/, { timeout: 15_000 });

		// Open Details
		await page.locator('tbody tr').first().click();
		await page.waitForURL(/.*journals\/\d+/);

		// Submit Journal
		await page.locator('button:has-text("Submit")').first().click();
		await page.locator('button:has-text("Yes, Submit Adjustment")').click();

		// Wait for submitted state
		await expect(page.locator('span:has-text("Submitted")').first()).toBeVisible({
			timeout: 10_000
		});

		// Relogin as Master to Approve, Post & Reverse
		await page.click('button[title="Sign out"]');
		await page.waitForURL(/.*login/);

		await page.fill('#email', 'admin@texas.com');
		await page.fill('#password', 'S3cure_Acc_999!');
		await page.click('button[type="submit"]');
		await page.waitForURL(/.*dashboard/);

		await page.goto('/accounting/journals');
		await page.locator('tbody tr').first().click();
		await page.waitForURL(/.*journals\/\d+/);

		// Approve
		await page.locator('button:has-text("Approve")').click();
		await page.locator('button:has-text("Approve Adjustment")').click();
		await expect(page.locator('span:has-text("Approved")').first()).toBeVisible({
			timeout: 10_000
		});

		// Relogin as Accountant to Post (as Post is RequireAccountant on backend)
		await page.click('button[title="Sign out"]');
		await page.waitForURL(/.*login/);

		await page.fill('#email', 'accountant@texas.com');
		await page.fill('#password', 'AccountantPass123!');
		await page.click('button[type="submit"]');
		await page.waitForURL(/.*dashboard/);

		await page.goto('/accounting/journals');
		await page.locator('tbody tr').first().click();
		await page.waitForURL(/.*journals\/\d+/);

		// Post
		await page.locator('button:has-text("Post Journal")').click();
		await page.locator('button:has-text("Confirm Ledger Posting")').click();
		await expect(page.locator('span:has-text("Posted")').first()).toBeVisible({
			timeout: 10_000
		});

		// Relogin as Master to Reverse
		await page.click('button[title="Sign out"]');
		await page.waitForURL(/.*login/);

		await page.fill('#email', 'admin@texas.com');
		await page.fill('#password', 'S3cure_Acc_999!');
		await page.click('button[type="submit"]');
		await page.waitForURL(/.*dashboard/);

		await page.goto('/accounting/journals');
		await page.locator('tbody tr').first().click();
		await page.waitForURL(/.*journals\/\d+/);

		// Reverse
		await page.locator('button:has-text("Reverse Journal")').click();
		await page.fill('#reversal-desc', 'Reversing transaction from automation test run.');
		await page.click('button:has-text("Execute Reversal")');
		await expect(page.locator('span:has-text("Reversed")').first()).toBeVisible({
			timeout: 10_000
		});
	});

